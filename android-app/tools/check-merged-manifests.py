#!/usr/bin/env python3
import pathlib
import sys
import xml.etree.ElementTree as ET

root = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(".")
android_ns = "{http://schemas.android.com/apk/res/android}"


def parse_variants(argv):
    """Optional --variants a,b filter.

    The Gradle build knows which variants it produced and passes them, so a stale
    merged manifest left behind by an earlier or aborted build is never checked
    against the current source. Without the flag every merged manifest found is
    checked, which is what the workflow callers rely on.
    """
    if "--variants" not in argv:
        return None
    index = argv.index("--variants")
    raw = argv[index + 1] if index + 1 < len(argv) else ""
    variants = {part.strip().lower() for part in raw.split(",") if part.strip()}
    return variants


requested_variants = parse_variants(sys.argv)
merged_root = "app/build/intermediates/merged_manifest"


def merged_manifests(pattern):
    """Merged manifests matching a glob, restricted to the requested variants."""
    found = []
    for path in root.glob(pattern):
        if requested_variants is None:
            found.append(path)
            continue
        try:
            variant = path.relative_to(root / merged_root).parts[0].lower()
        except (ValueError, IndexError):
            continue
        if variant in requested_variants:
            found.append(path)
    return found

# Verify source manifests
main_manifest = ET.parse(root / "app/src/main/AndroidManifest.xml").getroot()
play_source_manifest = ET.parse(root / "app/src/play/AndroidManifest.xml").getroot()
sideload_source_manifest = ET.parse(root / "app/src/githubSideload/AndroidManifest.xml").getroot()

def get_permissions(element):
    return {
        item.get(android_ns + "name")
        for item in element.findall("uses-permission")
    }

main_perms = get_permissions(main_manifest)
assert main_perms == {
    "android.permission.INTERNET",
    "android.permission.POST_NOTIFICATIONS",
    "android.permission.RECEIVE_BOOT_COMPLETED",
    "android.permission.VIBRATE",
}, f"main manifest unexpected perms: {main_perms}"

play_source_perms = get_permissions(play_source_manifest)
assert play_source_perms == set(), f"play source manifest should declare no extra perms: {play_source_perms}"

sideload_source_perms = get_permissions(sideload_source_manifest)
assert sideload_source_perms == {
    "android.permission.INTERNET",
    "android.permission.ACCESS_NETWORK_STATE",
    "android.permission.POST_PROMOTED_NOTIFICATIONS",
}, f"sideload source manifest unexpected perms: {sideload_source_perms}"

# Verify cleartext traffic enabled in main (owner-approved HTTP browsing, 2026-11-06)
main_app = main_manifest.find("application")
assert main_app.get(android_ns + "usesCleartextTraffic") == "true", "cleartext traffic must be true for HTTP browsing"

# Check merged manifests if they have been generated by Gradle
play_merged = merged_manifests(f"{merged_root}/play*/**/AndroidManifest.xml")
sideload_merged = merged_manifests(f"{merged_root}/githubSideload*/**/AndroidManifest.xml")

if requested_variants is not None:
    produced = set()
    for path in play_merged + sideload_merged:
        produced.add(path.relative_to(root / merged_root).parts[0].lower())
    missing = sorted(requested_variants - produced)
    assert not missing, (
        f"requested variant(s) produced no merged manifest: {missing}. "
        "The manifest was not generated, so it cannot be verified."
    )

if play_merged:
    play_merged_tree = ET.parse(play_merged[0]).getroot()
    play_perms = get_permissions(play_merged_tree)
    assert "android.permission.INTERNET" in play_perms, "Play merged manifest must retain INTERNET for WebView"
    assert "android.permission.ACCESS_NETWORK_STATE" not in play_perms, "Play merged manifest must NOT have ACCESS_NETWORK_STATE"
    assert play_perms == {
        "android.permission.INTERNET",
        "android.permission.POST_NOTIFICATIONS",
        "android.permission.RECEIVE_BOOT_COMPLETED",
        "android.permission.VIBRATE",
    }, f"Play merged manifest has unexpected extra permissions: {play_perms}"
    play_merged_app = play_merged_tree.find("application")
    assert play_merged_app.get(android_ns + "usesCleartextTraffic") == "true", "Play merged cleartext must be true"
    print("PASS Play merged manifest check: INTERNET=YES, reminder perms=YES, ACCESS_NETWORK_STATE=NO, cleartext=true")

if sideload_merged:
    sideload_merged_tree = ET.parse(sideload_merged[0]).getroot()
    sideload_perms = get_permissions(sideload_merged_tree)
    assert "android.permission.INTERNET" in sideload_perms, "Sideload merged manifest must have INTERNET"
    assert "android.permission.ACCESS_NETWORK_STATE" in sideload_perms, "Sideload merged manifest must have ACCESS_NETWORK_STATE"
    assert sideload_perms == {
        "android.permission.INTERNET",
        "android.permission.ACCESS_NETWORK_STATE",
        "android.permission.POST_NOTIFICATIONS",
        "android.permission.POST_PROMOTED_NOTIFICATIONS",
        "android.permission.RECEIVE_BOOT_COMPLETED",
        "android.permission.VIBRATE",
    }, f"Sideload merged manifest has unexpected extra permissions: {sideload_perms}"
    sideload_merged_app = sideload_merged_tree.find("application")
    assert sideload_merged_app.get(android_ns + "usesCleartextTraffic") == "true", "Sideload merged cleartext must be true"
    print("PASS Sideload merged manifest check: INTERNET=YES, ACCESS_NETWORK_STATE=YES, reminder perms=YES, optional promoted-notification permission=YES, cleartext=true")

print("PASS manifest architecture policy: Play inherits only shared WebView/reminder permissions; Sideload alone adds ACCESS_NETWORK_STATE and optional POST_PROMOTED_NOTIFICATIONS; Play never requests Live Update promotion")
